#!/usr/bin/env python3
"""Generate the AmaaraOS window decoration (xfwm4 theme).

xfwm4 themes are just PNGs plus a ``themerc``. Generating them means the window
chrome is part of the design system instead of a leftover from the distribution:
cream titlebars, one hairline, and macOS-positioned controls in our palette.

    python3 os/brand/make-xfwm-theme.py          # writes os/overlay/usr/share/themes/Amaara/xfwm4

Run it on a build host (needs Pillow) and commit the output: the appliance image
has no Pillow, and regenerating a theme must never be part of booting a box.

Layout of the decoration:

    ╭──────────────────────────────╮   cream, 8 px top corners
    │ ● ● ●        title           │   12 px controls at the left
    ╰──────────────────────────────╯   one hairline
    │                              │   1 px sides, 4 px bottom

Buttons: close is crimson, hide is amber, maximise is green — the three lights,
read as red/amber/green without copying anyone's exact pixels.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw

CREAM = (249, 244, 238, 255)
CREAM_INACTIVE = (242, 233, 224, 255)
INK = (11, 9, 8, 255)
MUTED = (110, 96, 88, 255)
HAIR = (228, 214, 202, 255)
RED = (215, 46, 53, 255)
AMBER = (224, 149, 47, 255)
GREEN = (47, 125, 79, 255)
GHOST = (216, 200, 187, 255)

TITLE_HEIGHT = 30
RADIUS = 8

THEMERC = """\
# AmaaraOS window decoration, generated by os/brand/make-xfwm-theme.py.
# Cream paper, one hairline, controls on the left like the desktop the rest of
# the world learned on. Do not hand-edit: change the generator.
active_text_color=#0B0908
inactive_text_color=#6E6058
title_shadow_active=false
title_shadow_inactive=false
title_font=Inter 10.5
title_vertical_offset_active=1
title_vertical_offset_inactive=1
button_offset=6
button_spacing=6
# All three controls on the left, in the order the desktop world reads them:
# close, minimise, maximise. The pipe is the split between the two titlebar sides.
button_layout=CHM|
full_width_title=true
title_alignment=center
maximized_offset=0
shadow_delta_height=0
shadow_delta_width=0
shadow_delta_x=0
shadow_delta_y=-3
shadow_opacity=40
"""


def rounded_top(width: int, height: int, fill, *, right: bool) -> Image.Image:
    """A titlebar end: one rounded corner, square on the side that meets the title."""
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    if right:
        draw.rounded_rectangle([-RADIUS, 0, width - 1, height + RADIUS], radius=RADIUS, fill=fill)
    else:
        draw.rounded_rectangle([0, 0, width + RADIUS, height + RADIUS], radius=RADIUS, fill=fill)
    # hairline under the titlebar
    draw.rectangle([0, height - 1, width, height], fill=HAIR)
    return img


def flat(width: int, height: int, fill, hairline: str | None = None) -> Image.Image:
    img = Image.new("RGBA", (width, height), fill)
    draw = ImageDraw.Draw(img)
    if hairline == "bottom":
        draw.rectangle([0, height - 1, width, height], fill=HAIR)
    elif hairline == "left":
        draw.rectangle([0, 0, 1, height], fill=HAIR)
    elif hairline == "right":
        draw.rectangle([width - 1, 0, width, height], fill=HAIR)
    return img


def control(kind: str, state: str) -> Image.Image:
    """A 22x22 traffic light. Glyphs only appear on hover, like a real desktop."""
    img = Image.new("RGBA", (22, 22), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    base = {"close": RED, "hide": AMBER, "maximize": GREEN, "shade": GHOST,
            "stick": GHOST, "menu": GHOST}[kind]
    if state == "inactive":
        base = GHOST
    elif state == "prelight":
        base = tuple(min(255, channel + 18) for channel in base[:3]) + (255,)
    elif state == "pressed":
        base = tuple(max(0, channel - 28) for channel in base[:3]) + (255,)
    draw.ellipse([4, 4, 17, 17], fill=base)
    if state in ("prelight", "pressed"):
        glyph = (255, 255, 255, 220)
        if kind == "close":
            draw.line([8, 8, 13, 13], fill=glyph, width=2)
            draw.line([13, 8, 8, 13], fill=glyph, width=2)
        elif kind in ("hide", "shade"):
            draw.line([8, 11, 13, 11], fill=glyph, width=2)
        elif kind == "maximize":
            draw.rectangle([8, 8, 13, 13], outline=glyph, width=2)
        elif kind in ("menu", "stick"):
            for y in (8, 10, 12):
                draw.line([8, y, 13, y], fill=glyph, width=1)
    return img


def build(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for state, fill in (("active", CREAM), ("inactive", CREAM_INACTIVE)):
        # title bar: 5 vertical slices; xfwm4 tiles 2/3/4 between the ends
        flat(30, TITLE_HEIGHT, fill, "bottom").save(out / f"title-1-{state}.png")
        flat(30, TITLE_HEIGHT, fill, "bottom").save(out / f"title-2-{state}.png")
        flat(30, TITLE_HEIGHT, fill, "bottom").save(out / f"title-3-{state}.png")
        flat(30, TITLE_HEIGHT, fill, "bottom").save(out / f"title-4-{state}.png")
        flat(30, TITLE_HEIGHT, fill, "bottom").save(out / f"title-5-{state}.png")
        rounded_top(24, TITLE_HEIGHT, fill, right=False).save(out / f"top-left-{state}.png")
        rounded_top(24, TITLE_HEIGHT, fill, right=True).save(out / f"top-right-{state}.png")
        flat(4, 24, fill, "left").save(out / f"left-{state}.png")
        flat(4, 24, fill, "right").save(out / f"right-{state}.png")
        flat(6, 6, fill).save(out / f"bottom-{state}.png")
        flat(8, 8, fill).save(out / f"bottom-left-{state}.png")
        flat(8, 8, fill).save(out / f"bottom-right-{state}.png")

    for kind in ("close", "hide", "maximize", "shade", "stick", "menu"):
        for state in ("active", "inactive", "prelight", "pressed"):
            control(kind, state).save(out / f"{kind}-{state}.png")

    (out / "themerc").write_text(THEMERC, encoding="utf-8")
    print(f"wrote {len(list(out.iterdir()))} files to {out}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("os/overlay/usr/share/themes/Amaara/xfwm4"),
    )
    build(parser.parse_args().out)
